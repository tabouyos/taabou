-- 医事課（LIVEWORKS DWH / PostgreSQL）から健診システム用の患者CSVを出すSQL
-- 実行するのは医事課・情報システム担当（DWHに接続できる人）。読み取りのみ。
-- ============================================================

-- ① 確認用：対象の件数
select count(*) as 件数
from "dwh_患者基本情報"
where coalesce("死亡区分", 0) <> 1 and "患者id" <> 0;

-- ② 書き出し用：結果をCSV（ヘッダー付き）で保存 → 健診システムの「📥 受診者CSV取込」で読み込む
--    カルテNo＝「患者id」で確定。診察券は8桁なので、先頭0埋めの8桁で出す（2026/10 相葉さん確認）
select lpad("患者id"::text, 8, '0') as "カルテ番号",
       "漢字氏名",
       "かな氏名"  as "カナ氏名",
       "生年月日",
       "性別"
from "dwh_患者基本情報"
where coalesce("死亡区分", 0) <> 1   -- 死亡の方は除く
  and "患者id" <> 0                  -- 無効データは除く
order by 1;
