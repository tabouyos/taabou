-- 医事課（LIVEWORKS DWH / PostgreSQL）から健診システム用の患者CSVを出すSQL
-- 実行するのは医事課・情報システム担当（DWHに接続できる人）。読み取りのみ。
-- ============================================================

-- ① 確認用：どちらの番号が「診察券のカルテNo」か、件数はどれくらいか
select "患者id", "患者番号", "漢字氏名"
from "dwh_患者基本情報"
limit 5;

select count(*) as 件数
from "dwh_患者基本情報"
where coalesce("死亡区分", 0) <> 1 and "患者id" <> 0;

-- ② 書き出し用：結果をCSV（ヘッダー付き）で保存 → 健診システムの「📥 受診者CSV取込」で読み込む
--    ※ カルテNoが「患者id」の方だった場合は、1行目の "患者番号" を "患者id" に変える
select "患者番号" as "カルテ番号",
       "漢字氏名",
       "かな氏名"  as "カナ氏名",
       "生年月日",
       "性別"
from "dwh_患者基本情報"
where coalesce("死亡区分", 0) <> 1   -- 死亡の方は除く
  and "患者id" <> 0                  -- 無効データは除く
order by 1;
